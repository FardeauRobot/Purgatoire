def java_round(v):
    return int(math.floor(v + 0.5))


def direction_ordinal(dx, dy):
    return ADJ4.index((dx, dy)) if (dx, dy) in ADJ4 else 4


def manhattan(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])


