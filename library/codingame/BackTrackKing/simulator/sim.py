class Bot:
    def __init__(self, command, index):
        self.command = command
        self.index = index
        self.active = True
        self.out = queue.Queue()
        self.err_lines = []
        self.lock = threading.Lock()
        self.proc = subprocess.Popen(
            shlex.split(command),
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, bufsize=1,
        )
        threading.Thread(target=self._pump_out, daemon=True).start()
        threading.Thread(target=self._pump_err, daemon=True).start()

    def _pump_out(self):
        for line in self.proc.stdout:
            self.out.put(line.rstrip("\n"))
        self.out.put(None)

    def _pump_err(self):
        for line in self.proc.stderr:
            with self.lock:
                self.err_lines.append(line.rstrip("\n"))

    def take_stderr(self):
        with self.lock:
            lines, self.err_lines = self.err_lines, []
        return "\n".join(lines)

    def ask(self, lines):
        """Sends a turn's input, returns (line or None, elapsed ms)."""
        start = time.perf_counter()
        try:
            self.proc.stdin.write("\n".join(map(str, lines)) + "\n")
            self.proc.stdin.flush()
        except (BrokenPipeError, OSError):
            return None, 0.0
        try:
            line = self.out.get(timeout=HARD_TIMEOUT_S)
        except queue.Empty:
            line = None
        return line, (time.perf_counter() - start) * 1000.0

    def kill(self):
        try:
            self.proc.kill()
            self.proc.wait(timeout=1)
        except Exception:
            pass


