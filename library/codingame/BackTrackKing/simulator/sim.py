PATTERNS = [
    ("AUTOPLACE", re.compile(r"AUTOPLACE ([0-9]+) ([0-9]+) ([0-9]+) ([0-9]+)", re.I)),
    ("PLACE", re.compile(r"PLACE_TRACKS ([0-9]+) ([0-9]+)", re.I)),
    ("DISRUPT", re.compile(r"DISRUPT ([0-9]+)", re.I)),
    ("DISRUPT_ALT", re.compile(r"DISRUPT ([0-9]+) ([0-9]+)", re.I)),
    ("MESSAGE", re.compile(r"MESSAGE ([^;]*)", re.I)),
    ("WAIT", re.compile(r"WAIT", re.I)),
]


def parse_commands(line):
    """Returns (intents, message, error). On error the intents parsed so far still apply."""
    text = line.strip()
    parts = text.split(";") if text else [""]
    while len(parts) > 0 and text and parts[-1] == "":
        parts.pop()
    intents, message = [], None
    for raw in parts:
        cmd = raw.strip()
        for kind, rx in PATTERNS:
            m = rx.fullmatch(cmd)
            if not m:
                continue
            g = [int(v) for v in m.groups()] if kind != "MESSAGE" else None
            if kind == "AUTOPLACE":
                intents.append({"type": kind, "from": (g[0], g[1]), "to": (g[2], g[3])})
            elif kind == "PLACE":
                intents.append({"type": kind, "at": (g[0], g[1])})
            elif kind == "DISRUPT":
                intents.append({"type": kind, "region": g[0]})
            elif kind == "DISRUPT_ALT":
                intents.append({"type": kind, "at": (g[0], g[1])})
            elif kind == "MESSAGE":
                message = m.group(1)
            break
        else:
            return intents, message, f"Invalid command: '{cmd}'"
    return intents, message, None


