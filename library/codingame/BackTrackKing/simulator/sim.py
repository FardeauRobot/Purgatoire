class Game:
    def __init__(self, gmap, league):
        self.league = league
        self.w, self.h = gmap["width"], gmap["height"]
        self.kind = [[int(ch) for ch in row] for row in gmap["types"]]
        self.region = [list(row) for row in gmap["regions"]]
        self.track = [[TRACK_NONE] * self.w for _ in range(self.h)]
        self.towns = gmap["towns"]
        self.town_at = {(t["x"], t["y"]): t["id"] for t in self.towns}

        n_regions = max(max(row) for row in self.region) + 1
        self.regions = [{"id": i, "coords": [], "towns": [], "instability": 0, "inked": False} for i in range(n_regions)]
        for y in range(self.h):
            for x in range(self.w):
                self.regions[self.region[y][x]]["coords"].append((x, y))
        for t in self.towns:
            self.regions[self.region[t["y"]][t["x"]]]["towns"].append(t["id"])

        self.scores = [0, 0]
        self.turn = 0
        self.paths = {}
        self.last_disrupt = {}  # never cleared, like succesfulBlotsThisTurn
        self.inked_enemy_track = False

    # -- helpers ----------------------------------------------------------

    def in_grid(self, c):
        return 0 <= c[0] < self.w and 0 <= c[1] < self.h

    def neighbours(self, c):
        return [(c[0] + dx, c[1] + dy) for dx, dy in ADJ4 if self.in_grid((c[0] + dx, c[1] + dy))]

    def track_at(self, c):
        return self.track[c[1]][c[0]]

    def region_of(self, c):
        return self.regions[self.region[c[1]][c[0]]]

    def track_or_town(self, c):
        return c in self.town_at or self.track_at(c) != TRACK_NONE

    # -- input serialisation (Serializer.java) ----------------------------

    def global_input(self, player):
        lines = [player, self.w, self.h]
        for y in range(self.h):
            for x in range(self.w):
                lines.append(f"{self.region[y][x]} {self.kind[y][x]}")
        lines.append(len(self.towns))
        for t in self.towns:
            desired = ",".join(map(str, t["desired"])) or "x"
            lines.append(f"{t['id']} {t['x']} {t['y']} {desired}")
        return lines

    def turn_input(self, player):
        on_cell = {}
        for (a, b), path in self.paths.items():
            for c in path:
                on_cell.setdefault(c, []).append(f"{a}-{b}")
        lines = [self.scores[player], self.scores[1 - player]]
        for y in range(self.h):
            for x in range(self.w):
                r = self.regions[self.region[y][x]]
                conns = ",".join(sorted(on_cell.get((x, y), []))) or "x"
                lines.append(f"{self.track[y][x]} {r['instability']} {1 if r['inked'] else 0} {conns}")
        return lines

    # -- turn resolution (performGameUpdate) ------------------------------

    def update(self, intents):
        self.turn += 1
        log, events = [], {"placed": [], "disrupted": [], "inked": []}

        def error(p, msg):
            log.append(f"P{p}: {msg}")

        dosh = [PAINT_PER_TURN, PAINT_PER_TURN]
        disrupts = [DISRUPT_PER_TURN, DISRUPT_PER_TURN]

        for p in (0, 1):
            resolved, used = [], False
            for a in intents[p]:
                if a["type"] != "AUTOPLACE":
                    resolved.append(a)
                elif used:
                    error(p, "Only one autobuild action allowed per turn.")
                else:
                    used = True
                    for c in self.autoplace(a["from"], a["to"]):
                        resolved.append({"type": "PLACE", "at": c, "auto": True})
            intents[p] = resolved

        placed, order = {}, []
        for p in (0, 1):
            interrupted = False
            for a in intents[p]:
                if a["type"] != "PLACE" or (interrupted and a.get("auto")):
                    continue
                c = a["at"]
                where = f"({c[0]}, {c[1]})"
                if not self.in_grid(c):
                    error(p, f"Not part of grid: {where}")
                    continue
                if c in self.town_at:
                    error(p, f"Cannot place tracks on a town at {where}")
                    continue
                if self.region_of(c)["inked"]:
                    error(p, f"Cannot build in region {self.region_of(c)['id']}")
                    continue
                if self.track_at(c) != TRACK_NONE or p in placed.get(c, []):
                    error(p, f"Cannot place tracks on existing tracks at {where}")
                    continue
                cost = RAIL_COST[self.kind[c[1]][c[0]]]
                if dosh[p] < cost:
                    if a.get("auto"):
                        error(p, f"Autobuild interrupted: not enough track points to build a track at {where}.")
                        interrupted = True
                    else:
                        error(p, f"Not enough track points to build a track at {where}.")
                    continue
                placed.setdefault(c, []).append(p)
                if c in order:
                    order.remove(c)
                order.append(c)
                dosh[p] -= cost
        for c in order:
            owner = placed[c][0] if len(placed[c]) == 1 else TRACK_NEUTRAL
            self.track[c[1]][c[0]] = owner
            events["placed"].append([c[0], c[1], owner])

        for p in (0, 1):
            for a in intents[p]:
                if a["type"] == "DISRUPT_ALT":
                    if not self.in_grid(a["at"]):
                        error(p, f"Not part of grid: ({a['at'][0]}, {a['at'][1]})")
                        continue
                    a["type"], a["region"] = "DISRUPT", self.region_of(a["at"])["id"]
                if a["type"] != "DISRUPT":
                    continue
                if disrupts[p] <= 0:
                    error(p, "Not enough disruption points.")
                    continue
                rid = a["region"]
                if rid >= len(self.regions):
                    error(p, f"Invalid region id: {rid}")
                    continue
                r = self.regions[rid]
                if r["inked"]:
                    error(p, f"Cannot disrupt region{rid}. Already inked out.")
                    continue
                if r["towns"]:
                    error(p, f"Cannot disrupt region{rid}. It contains a town.")
                    continue
                disrupts[p] -= 1
                r["instability"] += 1
                self.last_disrupt[p] = rid
                events["disrupted"].append([p, rid])

        for r in [r for r in self.regions if not r["inked"] and not r["towns"] and r["instability"] >= INK_THRESHOLD]:
            r["inked"] = True
            wiped = [0, 0, 0]
            for x, y in r["coords"]:
                if self.track[y][x] != TRACK_NONE:
                    wiped[self.track[y][x]] += 1
                    self.track[y][x] = TRACK_NONE
            if self.last_disrupt.get(0) == r["id"] and wiped[1] > 0:
                self.inked_enemy_track = True
            events["inked"].append(r["id"])
            log.append(f"Region {r['id']} inked out (wiped P0:{wiped[0]} P1:{wiped[1]} neutral:{wiped[2]})")

        old_paths = self.paths
        self.paths = {}
        connections = []
        for t in self.towns:
            for other in t["desired"]:
                path = self.train_path(t, self.towns[other])
                if not path:
                    if (t["id"], other) in old_paths:
                        log.append(f"Connection {t['id']}-{other} lost")
                    continue
                self.paths[(t["id"], other)] = path
                points = [0, 0]
                for x, y in path:
                    if self.track[y][x] in (0, 1):
                        points[self.track[y][x]] += 1
                self.scores[0] += points[0]
                self.scores[1] += points[1]
                if (t["id"], other) not in old_paths:
                    log.append(f"Connection {t['id']}-{other} formed ({len(path)} cells)")
                elif old_paths[(t["id"], other)] != path:
                    log.append(f"Connection {t['id']}-{other} rerouted ({len(path)} cells)")
                connections.append({"from": t["id"], "to": other, "path": [list(c) for c in path], "points": points})
        return log, events, connections

    def is_over(self):
        if self.league <= 2:
            return self.objective_complete() or self.turn >= MAX_TURNS
        return self.turn >= MAX_TURNS or not self.any_connection_possible()

    def objective_complete(self):
        if self.league == 1:
            return self.scores[0] >= 1
        if self.league == 2:
            return self.inked_enemy_track
        return False

    # -- pathfinding ------------------------------------------------------

    def train_path(self, a, b):
        """TrainBFS: shortest track/town path, neighbours tried N, E, S, W."""
        start, goal = (a["x"], a["y"]), (b["x"], b["y"])
        prev = {start: None}
        fifo = deque([start])
        while fifo:
            cur = fifo.popleft()
            if cur == goal:
                path = []
                while cur is not None:
                    path.append(cur)
                    cur = prev[cur]
                return path[::-1]
            for nb in self.neighbours(cur):
                if nb not in prev and self.track_or_town(nb):
                    prev[nb] = cur
                    fifo.append(nb)
        return []

    def any_connection_possible(self):
        for t in self.towns:
            for other in t["desired"]:
                if self.terrain_reachable((t["x"], t["y"]), (self.towns[other]["x"], self.towns[other]["y"])):
                    return True
        return False

    def terrain_reachable(self, start, goal):
        seen, fifo = {start}, deque([start])
        while fifo:
            cur = fifo.popleft()
            if cur == goal:
                return True
            for nb in self.neighbours(cur):
                if nb not in seen and not self.region_of(nb)["inked"]:
                    seen.add(nb)
                    fifo.append(nb)
        return False

    def rail_component(self, start):
        seen, fifo = {start}, deque([start])
        while fifo:
            cur = fifo.popleft()
            for nb in self.neighbours(cur):
                if nb not in seen and self.track_or_town(nb):
                    seen.add(nb)
                    fifo.append(nb)
        return seen

    def rail_block_boundary(self, start):
        out, seen, fifo = [], {start}, deque([start])
        while fifo:
            cur = fifo.popleft()
            if not self.track_or_town(cur):
                out.append(cur)
                continue
            for nb in self.neighbours(cur):
                if nb not in seen:
                    seen.add(nb)
                    fifo.append(nb)
        return out

    def autoplace(self, frm, to):
        """AutobuildAStar (heuristic is 0, so Dijkstra) on paint cost. Returns cells to place, in order."""
        if not self.in_grid(frm) or not self.in_grid(to):
            return []
        start = (frm, self.track_or_town(frm))
        g = {start: 0}
        came = {}
        tracks = {start: frozenset()}
        pq = JavaPriorityQueue()
        pq.add((0, 0, start))
        components = {}

        def is_goal(cursor):
            if cursor == to:
                return True
            if not self.track_or_town(cursor):
                return False
            if cursor not in components:
                comp = self.rail_component(cursor)
                for c in comp:
                    components[c] = comp
            return to in components[cursor]

        while pq:
            cost, _, key = pq.poll()
            if cost > g[key]:
                continue
            cursor = key[0]
            if is_goal(cursor):
                cells = []
                while key in came:
                    if key[1] and key[0] in tracks[key]:
                        cells.append(key[0])
                    key = came[key]
                return cells[::-1]

            mine = tracks[key]
            if cursor in mine:
                scope = self.neighbours(cursor)
            elif self.track_or_town(cursor):
                scope = self.rail_block_boundary(cursor)
            else:
                scope = [cursor]

            for nb in scope:
                if self.region_of(nb)["inked"] and nb not in self.town_at:
                    continue
                if nb in mine:
                    continue
                if self.track_or_town(nb):
                    if nb == cursor:
                        continue
                    step, next_tracks = 0, mine
                else:
                    step, next_tracks = RAIL_COST[self.kind[nb[1]][nb[0]]], mine | {nb}
                nkey = (nb, True)
                ng = g[key] + step
                if ng < g.get(nkey, math.inf):
                    came[nkey] = key
                    g[nkey] = ng
                    tracks[nkey] = next_tracks
                    pq.add((ng, direction_ordinal(nb[0] - cursor[0], nb[1] - cursor[1]), nkey))
        return []


