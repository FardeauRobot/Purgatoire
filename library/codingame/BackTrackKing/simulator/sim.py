class River:
    def __init__(self, coord, history, preferred):
        self.current = coord
        self.history = list(history) + [coord]
        self.preferred = preferred  # (dx, dy); (0, 0) means UNSET

    def is_start(self):
        return len(self.history) == 1


class MapMaker:
    def __init__(self, rng):
        self.rng = rng
        self.h = rng.randint(14, 20)
        self.w = java_round(self.h * 1.5)

    def in_grid(self, c):
        return 0 <= c[0] < self.w and 0 <= c[1] < self.h

    def neighbours(self, c, adj=ADJ4):
        return [(c[0] + dx, c[1] + dy) for dx, dy in adj if self.in_grid((c[0] + dx, c[1] + dy))]

    def is_edge(self, c):
        return c[0] == 0 or c[1] == 0 or c[0] == self.w - 1 or c[1] == self.h - 1

    def is_corner(self, c):
        return c[0] in (0, self.w - 1) and c[1] in (0, self.h - 1)

    def kind(self, c):
        return self.type[c[1]][c[0]]

    def set_kind(self, c, k):
        self.type[c[1]][c[0]] = k

    def accessible(self, c):
        return self.kind(c) == PLAINS

    def make(self):
        w, h, rng = self.w, self.h, self.rng
        self.type = [[PLAINS] * w for _ in range(h)]
        self.zone = [[-1] * w for _ in range(h)]
        cells = [(x, y) for y in range(h) for x in range(w)]
        self.free_borders = [c for c in cells if self.is_edge(c) and not self.is_corner(c)]
        self.free_coords = list(cells)
        rng.shuffle(self.free_borders)
        rng.shuffle(self.free_coords)

        self.make_mountains()
        self.make_rivers()
        tiles_per_zone = h // 2
        zones = self.make_zones(max(1, (h * w) // tiles_per_zone))
        towns = self.make_towns(zones, max(4, (h * w) // 50), tiles_per_zone)
        desired = self.make_connections(len(towns))

        return {
            "width": w,
            "height": h,
            "types": ["".join(str(k) for k in row) for row in self.type],
            "regions": [list(row) for row in self.zone],
            "towns": [{"id": i, "x": c[0], "y": c[1], "desired": desired[i]} for i, c in enumerate(towns)],
        }

    def make_mountains(self):
        rng = self.rng
        count = max(2, java_round(rng.random() * self.w * self.h * 0.04))
        for _ in range(count):
            size = rng.randint(2, 7)
            if not self.free_coords:
                return
            base = self.free_coords.pop(0)
            self.set_kind(base, MOUNTAIN)
            mountain = [base]
            if base in self.free_borders:
                self.free_borders.remove(base)
            for _ in range(size):
                cand = sorted({n for c in mountain for n in self.neighbours(c) if self.accessible(n)})
                if not cand:
                    break
                pick = cand[rng.randrange(len(cand))]
                self.set_kind(pick, MOUNTAIN)
                mountain.append(pick)
                if pick in self.free_borders:
                    self.free_borders.remove(pick)
                if pick in self.free_coords:
                    self.free_coords.remove(pick)

    def water_nearby(self, c, history):
        ignore = history[-2:]
        return any(self.kind(n) == RIVER for n in self.neighbours(c, ADJ8) if n not in ignore)

    def start_direction(self, c):
        if c[0] == 0:
            return (1, 0)
        if c[1] == 0:
            return (0, 1)
        if c[0] == self.w - 1:
            return (-1, 0)
        if c[1] == self.h - 1:
            return (0, -1)
        return (0, 0)

    def add_water(self, to_expand, river):
        to_expand.append(river)
        self.set_kind(river.current, RIVER)
        if river.current in self.free_coords:
            self.free_coords.remove(river.current)

    def make_rivers(self):
        rng, w, h = self.rng, self.w, self.h
        remaining = java_round(w * h * 0.07)
        sources = deque(self.free_borders)
        sources.appendleft((w // 2, h // 2) if rng.random() < 0.5 else (w // 2, h // 2 + 1))
        initial = True
        finished = []

        while remaining > 0 and sources:
            start = sources.popleft()
            if start in self.free_borders:
                self.free_borders.remove(start)
            if self.water_nearby(start, []):
                continue
            to_expand = deque()
            self.add_water(to_expand, River(start, [], self.start_direction(start)))
            remaining -= 1

            while to_expand:
                river = to_expand.popleft()
                cur = river.current
                if self.is_edge(cur) and not river.is_start():
                    finished.append(river)
                    continue
                neighs = [
                    n for n in self.neighbours(cur)
                    if not self.water_nearby(n, river.history)
                    and self.kind(n) != RIVER
                    and (not river.is_start() or not self.is_edge(n))
                    and self.accessible(n)
                ]
                if not neighs:
                    finished.append(river)
                    continue

                split = remaining > 0 and len(neighs) >= 2 and rng.random() <= 0.055
                split = split or initial
                initial = False

                nxt = self.weighted_pick(river, neighs)
                delta = (nxt[0] - cur[0], nxt[1] - cur[1])
                self.add_water(to_expand, River(nxt, river.history, delta if split else river.preferred))
                remaining -= 1
                if not split:
                    continue

                others = [n for n in neighs if n != nxt]
                rng.shuffle(others)
                if not others:
                    continue
                branch = others[0]
                self.add_water(to_expand, River(branch, river.history, (branch[0] - cur[0], branch[1] - cur[1])))
                remaining -= 1

        for river in finished:
            if len(river.history) < 3:
                for c in river.history:
                    self.set_kind(c, PLAINS)

    def weighted_pick(self, river, neighs):
        pdx, pdy = river.preferred
        weights = []
        for n in neighs:
            d = (n[0] - river.current[0], n[1] - river.current[1])
            if d == (pdx, pdy):
                weights.append(1.75)
            elif d == (-pdx, -pdy):
                weights.append(0.25)
            else:
                weights.append(1.0)
        roll = self.rng.random() * sum(weights)
        acc = 0.0
        for n, wgt in zip(neighs, weights):
            acc += wgt
            if roll < acc:
                return n
        return neighs[0]

    def make_zones(self, n):
        w, h, rng = self.w, self.h, self.rng
        cols = math.ceil(math.sqrt(n))
        rows = math.ceil(n / cols)
        cell_h = h / rows
        zones = []
        for i in range(n):
            row, col = divmod(i, cols)
            if row == rows - 1 and n % cols != 0:
                cell_w = w / (n % cols)
            else:
                cell_w = w / cols
            c = (int((col + 0.5) * cell_w), int((row + 0.5) * cell_h))
            self.zone[c[1]][c[0]] = i
            zones.append({"id": i, "coords": [c], "neighbours": set()})

        blocked = set()
        zid = 0
        while True:
            if zid not in blocked:
                z = zones[zid]
                cand = sorted({nb for c in z["coords"] for nb in self.neighbours(c) if self.zone[nb[1]][nb[0]] == -1})
                if not cand:
                    blocked.add(zid)
                    if len(blocked) == n:
                        break
                else:
                    pick = cand[rng.randrange(len(cand))]
                    self.zone[pick[1]][pick[0]] = zid
                    z["coords"].append(pick)
            zid = (zid + 1) % n

        for z in zones:
            for c in z["coords"]:
                for nb in self.neighbours(c):
                    other = self.zone[nb[1]][nb[0]]
                    if other != z["id"]:
                        z["neighbours"].add(other)
        return zones

    def make_towns(self, zones, n_towns, tiles_per_zone):
        rng = self.rng
        available = list(zones)
        blacklist = set()
        towns = []
        step = max(1, 50 // tiles_per_zone)
        retries = 100

        def far_enough(c):
            return all(manhattan(c, t) >= MIN_TOWN_DISTANCE for t in towns)

        i = 0
        while i < n_towns:
            index = rng.randint(i * step, (i + 1) * step - 1)
            z = available[index % len(available)]
            found = False
            if z["id"] not in blacklist:
                coords = list(z["coords"])
                rng.shuffle(coords)
                for c in coords:
                    if self.accessible(c) and not self.is_edge(c) and far_enough(c):
                        towns.append(c)
                        found = True
                        blacklist.add(z["id"])
                        blacklist.update(z["neighbours"])
                        break
            if not found and retries > 0:
                retries -= 1
            else:
                i += 1

        rest = [z for z in available if z["id"] not in blacklist]
        rng.shuffle(rest)
        for _ in range(n_towns - len(towns)):
            if not rest:
                break
            z = rest.pop(0)
            coords = list(z["coords"])
            rng.shuffle(coords)
            for c in coords:
                if far_enough(c):
                    towns.append(c)
                    break

        for c in towns:
            self.set_kind(c, PLAINS)
        return towns

    def make_connections(self, n):
        rng = self.rng
        desired = {}
        for t in range(n):
            others = [o for o in range(n) if o != t]
            rng.shuffle(others)
            at_least = min(3, len(others))
            at_most = max(at_least, len(others) - 4)
            desired[t] = sorted(others[:rng.randint(at_least, at_most)])
        # Sequential on purpose: of a mutual pair, only the later town keeps its wish.
        for t in range(n):
            desired[t] = [o for o in desired[t] if t not in desired[o]]
        return desired


# --------------------------------------------------------------------------
# java.util.PriorityQueue — AUTOPLACE breaks equal-cost ties by heap layout
# --------------------------------------------------------------------------

class JavaPriorityQueue:
    def __init__(self):
        self.q = []

    @staticmethod
    def cmp(a, b):
        ka, kb = (a[0], a[1]), (b[0], b[1])
        return (ka > kb) - (ka < kb)

    def __bool__(self):
        return bool(self.q)

    def add(self, item):
        q = self.q
        q.append(item)
        k = len(q) - 1
        while k > 0:
            parent = (k - 1) >> 1
            if self.cmp(item, q[parent]) >= 0:
                break
            q[k] = q[parent]
            k = parent
        q[k] = item

    def poll(self):
        q = self.q
        result = q[0]
        x = q.pop()
        n = len(q)
        if n > 0:
            k, half = 0, n >> 1
            while k < half:
                child = 2 * k + 1
                if child + 1 < n and self.cmp(q[child], q[child + 1]) > 0:
                    child += 1
                if self.cmp(x, q[child]) <= 0:
                    break
                q[k] = q[child]
                k = child
            q[k] = x
        return result


