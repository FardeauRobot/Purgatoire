PLAINS, RIVER, MOUNTAIN = 0, 1, 2
TRACK_NONE, TRACK_NEUTRAL = -1, 2
ADJ4 = [(0, -1), (1, 0), (0, 1), (-1, 0)]  # N E S W — the referee's priority order
ADJ8 = ADJ4 + [(-1, -1), (1, 1), (1, -1), (-1, 1)]

MAX_TURNS = 100
PAINT_PER_TURN = 3
DISRUPT_PER_TURN = 1
