def load_or_make_map(args, seed):
    if args.map:
        with open(args.map) as f:
            return json.load(f)
    return MapMaker(random.Random(seed)).make()


def play(args, seed, bot_cmd, opp_cmd, swap, record):
    gmap = load_or_make_map(args, seed)
    game = Game(gmap, args.league)
    max_turns = args.max_turns or MAX_TURNS
    cmds = [opp_cmd, bot_cmd] if swap else [bot_cmd, opp_cmd]
    bots = [Bot(cmds[0], 0), Bot(cmds[1], 1)]
    you = 1 if swap else 0

    turns = []
    if record:
        turns.append(snapshot(game, [], [], {"placed": [], "disrupted": [], "inked": []},
                              ["", ""], [None, None], ["", ""], [0, 0]))
    end_reason = None
    try:
        while True:
            outputs, messages, timing, stderr = ["", ""], [None, None], [0.0, 0.0], ["", ""]
            intents = [[], []]
            log = []
            for b in bots:
                if not b.active:
                    continue
                lines = (game.global_input(b.index) if game.turn == 0 else []) + game.turn_input(b.index)
                line, ms = b.ask(lines)
                timing[b.index] = round(ms, 2)
                budget = FIRST_TURN_MS if game.turn == 0 else TURN_MS
                if line is None:
                    b.active = False
                    log.append(f"P{b.index}: timeout — no output line (crashed or > {HARD_TIMEOUT_S:.0f}s)")
                    continue
                outputs[b.index] = line
                if ms > budget:
                    if args.strict_timing:
                        b.active = False
                        log.append(f"P{b.index}: timeout — {ms:.1f} ms > {budget} ms")
                        continue
                    log.append(f"P{b.index}: slow turn — {ms:.1f} ms > {budget} ms (lenient)")
                parsed, msg, err = parse_commands(line)
                intents[b.index], messages[b.index] = parsed, msg
                if err:
                    b.active = False
                    log.append(f"P{b.index}: {err} — disqualified")
            time.sleep(0.002)
            for b in bots:
                stderr[b.index] = b.take_stderr()

            turn_log, events, connections = game.update(intents)
            log += turn_log
            if record:
                turns.append(snapshot(game, log, connections, events, outputs, messages, stderr, timing))

            if not all(b.active for b in bots):
                end_reason = "disqualified / timeout"
                break
            if game.is_over():
                if args.league <= 2:
                    end_reason = "objective complete" if game.objective_complete() else "turn limit — objective failed"
                elif game.turn >= MAX_TURNS:
                    end_reason = "turn limit"
                else:
                    end_reason = "no desired connection still possible"
                break
            if game.turn >= max_turns:
                end_reason = f"--max-turns {max_turns} reached"
                break
    finally:
        for b in bots:
            b.kill()

    final = list(game.scores)
    if args.league <= 2:
        winner = 0 if game.objective_complete() else 1
    else:
        for b in bots:
            if not b.active:
                final[b.index] = -1
        winner = 0 if final[0] > final[1] else 1 if final[1] > final[0] else -1

    result = {
        "seed": seed, "league": args.league, "you": you, "winner": winner,
        "you_won": winner == you, "draw": winner == -1,
        "scores": final, "turns": game.turn, "end_reason": end_reason,
        "players": cmds,
    }
    replay = None
    if record:
        replay = {
            "summary": result,
            "width": game.w, "height": game.h,
            "types": gmap["types"], "regions": gmap["regions"], "towns": gmap["towns"],
            "turns": turns,
        }
    return result, replay


def snapshot(game, log, connections, events, outputs, messages, stderr, timing):
    glyph = {TRACK_NONE: ".", 0: "0", 1: "1", TRACK_NEUTRAL: "2"}
    return {
        "turn": game.turn,
        "tracks": ["".join(glyph[v] for v in row) for row in game.track],
        "instability": [r["instability"] for r in game.regions],
        "inked": [r["id"] for r in game.regions if r["inked"]],
        "scores": list(game.scores),
        "connections": connections,
        "events": events,
        "commands": outputs,
        "messages": messages,
        "stderr": stderr,
        "timing_ms": timing,
        "log": log,
    }


def describe(r):
    who = "you" if r["you"] == 0 else "you (as P1)"
    if r["draw"]:
        verdict = "DRAW"
    else:
        verdict = "WIN " if r["you_won"] else "LOSS"
    return (f"[league {r['league']} seed {r['seed']}] {verdict}  scores P0={r['scores'][0]} P1={r['scores'][1]}  "
            f"turns={r['turns']}  ({r['end_reason']}; {who})")


def main():
    ap = argparse.ArgumentParser(description="Local referee for CodinGame Back Track King (Summer Challenge 2026).")
    ap.add_argument("--league", type=int, default=3, choices=[1, 2, 3],
                    help="1: connect two towns, 2: ink an enemy track, 3: full game (Bronze+)")
    ap.add_argument("--bot", help="command running your bot, e.g. ./main")
    ap.add_argument("--opponent", help="command running the opponent (default: the league's boss)")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--map", help="load a map JSON instead of generating one")
    ap.add_argument("--dump-map", metavar="PATH", help="write the generated map JSON and exit")
    ap.add_argument("--out", help="write a replay JSON for the viewer")
    ap.add_argument("--max-turns", type=int, help="stop early (does not change scoring rules)")
    ap.add_argument("--strict-timing", action="store_true", help="a turn over budget is a timeout loss, as on CodinGame")
    ap.add_argument("--swap", action="store_true", help="play as player 1 (league 3 only)")
    ap.add_argument("--games", type=int, help="play N games on seeds seed..seed+N-1, alternating sides in league 3")
    args = ap.parse_args()

    if args.dump_map:
        gmap = MapMaker(random.Random(args.seed)).make()
        with open(args.dump_map, "w") as f:
            json.dump(gmap, f, indent=1)
        print(f"map (seed {args.seed}, {gmap['width']}x{gmap['height']}, {len(gmap['towns'])} towns) -> {args.dump_map}")
        return
    if not args.bot:
        ap.error("--bot is required")
    if args.league <= 2 and args.swap:
        ap.error("--swap only makes sense in league 3: tutorial objectives are checked for player 0")

    opponent = args.opponent or DEFAULT_OPPONENT[args.league]

    if args.games:
        tally = {"win": 0, "loss": 0, "draw": 0}
        for i in range(args.games):
            swap = args.league == 3 and i % 2 == 1
            r, _ = play(args, args.seed + i, args.bot, opponent, swap, record=False)
            tally["draw" if r["draw"] else "win" if r["you_won"] else "loss"] += 1
            print(describe(r), flush=True)
        total = args.games
        print(f"\n{tally['win']}W {tally['loss']}L {tally['draw']}D over {total} games "
              f"({100 * tally['win'] / total:.0f}% wins)")
        return

    result, replay = play(args, args.seed, args.bot, opponent, args.swap, record=bool(args.out))
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w") as f:
            json.dump(replay, f, separators=(",", ":"))
    print(describe(result) + (f"  -> {args.out}" if args.out else ""))


if __name__ == "__main__":
    main()
